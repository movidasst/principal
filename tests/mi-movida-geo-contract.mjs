assert.match(app,/geo-credential-embed/);
assert.match(app,/referrerpolicy="strict-origin-when-cross-origin"/);
assert.match(app,/event\.origin!==GEO_FRAME_ORIGIN/);
assert.match(app,/event\.source!==frame\.contentWindow/);
assert.match(app,/\/api\/me\/credential-card/);
assert.match(app,/movida-geo-credential-ready/);
assert.match(app,/movida-geo-credential-data/);
